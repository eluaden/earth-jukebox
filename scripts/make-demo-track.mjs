// Generates public/tracks/demo-synthetic/track.json.
// THIS IS SYNTHETIC DATA for testing the audio engine. It is NOT a NASA measurement.
// Deterministic (seeded) so everyone on the team hears the same thing.
import { writeFileSync } from 'node:fs';

function mulberry32(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(42);
const round = (v) => Math.round(Math.min(1, Math.max(0, v)) * 1000) / 1000;

const years = Array.from({ length: 45 }, (_, i) => 1979 + i); // 45 frames
const n = years.length;
// "level": slow decline with wobble. "stress": rises as level falls.
const level = years.map((_, i) => {
  const t = i / (n - 1);
  return round(0.88 - 0.55 * Math.pow(t, 1.4) + 0.06 * Math.sin(i * 0.9) + (rand() - 0.5) * 0.08);
});
const stress = level.map((v, i) => round(1 - v + (rand() - 0.5) * 0.1 - 0.05 + 0.1 * (i / n)));

const minFrame = level.indexOf(Math.min(...level));
const events = [];
years.forEach((y, i) => {
  if (y % 10 === 0) events.push({ frame: i, type: 'milestone', say: { en: `${y}`, pt: `${y}`, es: `${y}` } });
});
events.push({
  frame: minFrame,
  type: 'record',
  say: {
    en: `${years[minFrame]}, lowest value in this synthetic series`,
    pt: `${years[minFrame]}, menor valor desta série sintética`,
    es: `${years[minFrame]}, valor más bajo de esta serie sintética`,
  },
});
events.sort((a, b) => a.frame - b.frame);

const track = {
  id: 'demo-synthetic',
  placeholder: true,
  title: {
    en: 'Synthetic demo (not real data)',
    pt: 'Demonstração sintética (dados não reais)',
    es: 'Demostración sintética (datos no reales)',
  },
  source: 'PLACEHOLDER — synthetic series generated by scripts/make-demo-track.mjs (seed 42). Not a NASA dataset.',
  secondsPerFrame: 0.5,
  frames: [],
  labels: years.map(String),
  series: { level, stress },
  mapping: {
    level: {
      layer: 'drone',
      meaning: {
        en: 'Higher, louder tone = higher level',
        pt: 'Tom mais agudo e mais forte = nível mais alto',
        es: 'Tono más agudo y más fuerte = nivel más alto',
      },
      legend: {
        min: { en: 'This is the lowest level.', pt: 'Este é o nível mais baixo.', es: 'Este es el nivel más bajo.' },
        max: { en: 'This is the highest level.', pt: 'Este é o nível mais alto.', es: 'Este es el nivel más alto.' },
      },
    },
    stress: {
      layer: 'texture',
      loudWhen: 'high',
      meaning: {
        en: 'Louder, brighter wind = more stress',
        pt: 'Vento mais forte e mais brilhante = mais estresse',
        es: 'Viento más fuerte y más brillante = más estrés',
      },
      legend: {
        min: { en: 'This is the least stress.', pt: 'Este é o menor estresse.', es: 'Este es el menor estrés.' },
        max: { en: 'This is the most stress.', pt: 'Este é o maior estresse.', es: 'Este es el mayor estrés.' },
      },
    },
  },
  events,
  narration: {
    intro: {
      en: 'Synthetic demo. These numbers are invented to test the sound. Each tick is one year, from 1979 to 2023.',
      pt: 'Demonstração sintética. Estes números são inventados para testar o som. Cada tique é um ano, de 1979 a 2023.',
      es: 'Demostración sintética. Estos números son inventados para probar el sonido. Cada tic es un año, de 1979 a 2023.',
    },
    outro: {
      en: 'End of the synthetic demo.',
      pt: 'Fim da demonstração sintética.',
      es: 'Fin de la demostración sintética.',
    },
  },
};

const out = new URL('../public/tracks/demo-synthetic/track.json', import.meta.url);
writeFileSync(out, JSON.stringify(track, null, 2) + '\n');
console.log(`wrote ${out.pathname} — ${n} frames, record low at ${years[minFrame]}`);
